"""Generate transport metadata and policy-free bridges around one WSGI application."""
import pprint

HEADER = '# Generated by scripts/build/generate_data_models.py; DO NOT EDIT.\n'


def generate(api):
    policy = api['x-http-policy']
    if (set(policy) != {'api-prefix', 'request-content-type', 'origin', 'response-headers'}
            or policy['origin'] != 'same-origin-if-present'
            or policy['request-content-type'] != 'application/json'
            or policy['api-prefix'] != '/api/'
            or policy['response-headers'] != {'Content-Type':'application/json; charset=utf-8', 'Cache-Control':'no-store'}):
        raise ValueError('Unsupported shared HTTP policy')
    requests, responses = {}, {}
    for path, methods in api['paths'].items():
        if not path.startswith(policy['api-prefix']): raise ValueError('API route outside declared prefix')
        for method, operation in methods.items():
            body = operation.get('requestBody')
            requests[path, method.upper()] = body['content'][policy['request-content-type']]['schema']['$ref'].split('/')[-1] if body else None
            for status, response in operation['responses'].items():
                responses[path, method.upper(), int(status)] = response['content']['application/json']['schema']['$ref'].split('/')[-1]
            for status in (400,403,500):
                if responses.get((path,method.upper(),status)) != 'ApiError':
                    raise ValueError('Every HTTP operation must declare shared admission and failure responses')
    unknown = api['x-unknown-route-response']
    metadata = HEADER + 'REQUESTS = ' + pprint.pformat(requests) + '\nRESPONSES = ' + pprint.pformat(responses)
    metadata += '\nPOLICY = ' + repr(policy) + '\nUNKNOWN_RESPONSE = ' + repr((unknown['status'], unknown['schema']['$ref'].split('/')[-1])) + '\n'
    return {'inside_inference/delivery/http_generated.py':metadata,
            'scripts/dev/http_runtimes_generated.py':HEADER + RUNTIMES}


